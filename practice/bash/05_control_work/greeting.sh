#!/bin/bash
# Проверочная работа по Bash — задание 1.
# Запрашивает ФИО и печатает приветствие.

read -r -p "Введите ваше ФИО и группу: " full_name

if [ -z "$full_name" ]; then
    echo "Строка не может быть пустой." >&2
    exit 1
fi

echo "Привет, $full_name! Добро пожаловать в мир Bash!"
echo "Скрипт запущен: $(date '+%d.%m.%Y %H:%M')"
