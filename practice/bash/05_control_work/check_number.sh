#!/bin/bash
# Проверочная работа по Bash — задание 3.
# Определяет знак числа, переданного аргументом.
# Сравнение через awk — работает и для целых, и для дробных.

if [ -z "$1" ]; then
    echo "Использование: $0 <число>" >&2
    exit 1
fi

value="$1"

if [[ ! "$value" =~ ^-?[0-9]+([.][0-9]+)?$ ]]; then
    echo "Ошибка: '$value' не является числом." >&2
    exit 1
fi

verdict=$(awk -v v="$value" 'BEGIN {
    if (v > 0)      print "положительным";
    else if (v < 0) print "отрицательным";
    else            print "нулём";
}')

echo "Число $value является $verdict"
